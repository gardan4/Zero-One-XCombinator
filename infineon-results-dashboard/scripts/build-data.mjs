import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(here, "..");
const repoRoot = process.env.ZERO_ONE_REPO || "/root/Zero-One-XCombinator";
const dataDir = resolve(repoRoot, "data/industrial-infineon/training_data");
const outPath = resolve(projectRoot, "src/data/fab-data.js");
const families = ["IC", "IGBT", "MOSFET"];

function parseCsv(text) {
  const rows = [];
  let row = [];
  let cell = "";
  let quoted = false;

  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    const next = text[i + 1];

    if (quoted) {
      if (ch === '"' && next === '"') {
        cell += '"';
        i += 1;
      } else if (ch === '"') {
        quoted = false;
      } else {
        cell += ch;
      }
      continue;
    }

    if (ch === '"') {
      quoted = true;
    } else if (ch === ",") {
      row.push(cell);
      cell = "";
    } else if (ch === "\n") {
      row.push(cell);
      rows.push(row);
      row = [];
      cell = "";
    } else if (ch !== "\r") {
      cell += ch;
    }
  }
  if (cell || row.length) {
    row.push(cell);
    rows.push(row);
  }
  return rows.filter((r) => r.some((c) => c.trim()));
}

function readSequences(family) {
  const path = resolve(dataDir, `${family}_variants.csv`);
  const rows = parseCsv(readFileSync(path, "utf8").replace(/^\uFEFF/, ""));
  const header = rows.shift().map((h) => h.trim().replace(/^\uFEFF/, ""));
  const seqIdx = header.indexOf("SEQUENCE_ID");
  const stepIdx = header.indexOf("STEP");
  if (seqIdx < 0 || stepIdx < 0) {
    throw new Error(`Unexpected CSV header in ${path}: ${header.join(",")}`);
  }

  const grouped = new Map();
  for (const row of rows) {
    const id = (row[seqIdx] || "").trim();
    const step = (row[stepIdx] || "").trim();
    if (!id || !step) continue;
    if (!grouped.has(id)) grouped.set(id, []);
    grouped.get(id).push(step);
  }
  return [...grouped.values()];
}

const raw = {};
const stepSet = new Set();
for (const family of families) {
  raw[family] = readSequences(family);
  for (const seq of raw[family]) {
    for (const step of seq) stepSet.add(step);
  }
}

const vocab = [...stepSet].sort();
const ids = new Map(vocab.map((step, i) => [step, i]));
const sequences = {};
const stats = {};

for (const family of families) {
  sequences[family] = raw[family].map((seq) => seq.map((step) => ids.get(step)));
  const lengths = raw[family].map((seq) => seq.length);
  stats[family] = {
    sequences: raw[family].length,
    minLength: Math.min(...lengths),
    maxLength: Math.max(...lengths),
    meanLength: Math.round((lengths.reduce((a, b) => a + b, 0) / lengths.length) * 10) / 10,
  };
}

const data = {
  generatedAt: new Date().toISOString(),
  source: "data/industrial-infineon/training_data/*_variants.csv",
  families,
  vocab,
  sequences,
  stats,
};

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(
  outPath,
  `// Generated by scripts/build-data.mjs. Do not edit by hand.\nexport const FAB_DATA = ${JSON.stringify(data)};\n`,
);

console.log(`Wrote ${outPath}`);
console.log(`Families: ${families.map((f) => `${f}=${stats[f].sequences}`).join(", ")}`);
console.log(`Vocab: ${vocab.length} step tokens`);
